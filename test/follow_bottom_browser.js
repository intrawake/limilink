// Disposable fixture; layout/scroll only, with no chat POSTs or provider calls.
async page => {
    if (!page.url().startsWith('http://127.0.0.1:11012/')) throw new Error('Use the isolated fixture.');
    const check = (condition, message) => { if (!condition) throw new Error(message); };
    await page.setViewportSize({ width: 1440, height: 900 });
    let busy = false, revision = 1, posts = 0;
    let history = Array.from({ length: 35 }, (_, i) => ({ role: 'bot', content: `Message ${i}\n${'A readable sentence that wraps when the Activity panel takes some width. '.repeat(12)}` }));
    const countPosts = request => { if (request.method() === 'POST' && request.url().endsWith('/chat')) posts++; };
    page.on('request', countPosts);
    await page.route('**/sessions/session_a/snapshot*', route => route.fulfill({ json: { session_id: 'session_a', revision: String(revision), history, busy, busy_sessions: busy ? ['session_a'] : [] } }));
    await page.goto(page.url());
    await page.waitForFunction(() => !document.querySelector('#new-session-btn').disabled);
    await page.locator('.session-row[data-session-id="session_a"] .session-link').click();
    await page.waitForFunction(() => activeSnapshot === null);
    check(await page.locator('#rename-current').count() === 0, 'Rename remains in chat header');
    await page.locator('.session-row[data-session-id="session_a"] summary').click();
    await page.locator('.session-row[data-session-id="session_a"]').getByRole('button', { name: 'Rename', exact: true }).click();
    await page.locator('#session-title-input').fill('Scroll follow fixture');
    await page.getByRole('button', { name: 'Save title', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('#rename-dialog').open);
    check(await page.locator('#session-title').textContent() === 'Scroll follow fixture', 'Menu rename did not save');
    const flush = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const measure = () => page.evaluate(() => {
        const chat = document.querySelector('#chat-container');
        return { gap: chat.scrollHeight - chat.clientHeight - chat.scrollTop, top: chat.scrollTop, height: chat.clientHeight, following: isScrolledToBottom };
    });
    const measurements = [];
    const record = async label => { await flush(); measurements.push({ label, ...await measure() }); };
    await record('initial');
    await page.locator('#message-input').fill(Array.from({ length: 10 }, (_, i) => `Draft line ${i}`).join('\n'));
    await record('taller draft');
    busy = true;
    await page.evaluate(() => syncSnapshot({ force: true }));
    await record('typing indicator');
    await page.locator('#activity-toggle').click();
    await record('Activity width change');
    history = [...history, { role: 'bot', content: 'New reply while following.\n'.repeat(8) }]; revision++;
    await page.evaluate(() => syncSnapshot({ force: true }));
    await record('new reply');
    busy = false;
    await page.evaluate(() => syncSnapshot({ force: true }));
    await page.locator('#message-input').fill('');
    await record('typing/draft collapse');
    // Reading older content must opt out of following, across replies and layout changes.
    await page.locator('#chat-container').evaluate(node => { node.scrollTop = 430; });
    await flush();
    const reading = await measure();
    check(!reading.following, 'Scrolling up did not release bottom following');
    await page.locator('#message-input').fill('Reading draft\n'.repeat(10));
    await flush();
    history = [...history, { role: 'bot', content: 'Reply while reading older messages' }]; revision++;
    await page.evaluate(() => syncSnapshot({ force: true }));
    await flush();
    const afterReadingReply = await measure();
    check(Math.abs(reading.top - afterReadingReply.top) <= 1 && !afterReadingReply.following, 'Reply/layout change pulled reader down');
    await page.locator('#activity-close').click();
    await flush();
    check(!((await measure()).following), 'Closing Activity re-enabled following while reading');
    // Returning to the bottom opts back in, including phone viewport/keyboard resizing.
    await page.locator('#chat-container').evaluate(node => { node.scrollTop = node.scrollHeight; });
    await flush();
    check((await measure()).following, 'Returning to bottom did not resume following');
    await page.setViewportSize({ width: 390, height: 844 });
    await record('phone reflow');
    await page.locator('#sidebar-toggle').click();
    await page.locator('.session-row[data-session-id="session_a"] summary').click();
    await page.locator('.session-row[data-session-id="session_a"]').getByRole('button', { name: 'Rename', exact: true }).click();
    await page.locator('#session-title-input').fill('Phone menu rename');
    await page.getByRole('button', { name: 'Save title', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('#rename-dialog').open);
    check(await page.locator('#session-title').textContent() === 'Phone menu rename', 'Phone menu rename did not save');
    await page.locator('#sidebar-close').click();
    await page.setViewportSize({ width: 390, height: 530 });
    await record('phone keyboard-sized viewport');
    await page.setViewportSize({ width: 390, height: 844 });
    await record('phone viewport restored');
    history = [...history, { role: 'bot', content: 'Last phone reply\n'.repeat(9) }]; revision++;
    await page.evaluate(() => syncSnapshot({ force: true }));
    await record('phone reply');
    await page.unroute('**/sessions/session_a/snapshot*'); page.off('request', countPosts);
    await page.setViewportSize({ width: 1440, height: 900 });
    const passed = measurements.every(item => item.gap <= 2 && item.following);
    check(posts === 0, 'Scroll checking sent a chat message');
    check(passed, `Bottom following failed: ${JSON.stringify(measurements)}`);
    return { passed, measurements, readingPositionPreserved: true, providers: 0, chatPosts: posts };
}
